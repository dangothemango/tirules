<h2><a href="/R_action_cards">Action Cards</a></h2>
<ul>
    <li>If a player has more than seven action cards, they must discard the excess.<sup>1,2,3</sup>
        <ul>
        <li><b>Explicit</b>: <sup>3</sup> Learn to Play: &ldquo;If a player exceeds this number, they must choose which seven cards they wish to keep and discard the rest.&rdquo;</li>
        </ul></li>
</ul>
<h2><a href="/R_active_player">Active Player</a></h2>
<ul>
    <li>During combat, the active player is the attacker.<sup>1,3</sup>
        <ul>
        <li><b>Explicit</b>: <sup>3</sup> Learn to Play: &ldquo;During combat, the active player is the attacker and the other player is the defender.&rdquo;</li>
        </ul></li>
</ul>
<h2><a href="/R_agenda_phase">Agenda Phase</a></h2>
<ul>
    <li>Each pair of players may resolve one transaction during each agenda.<sup>1,2,3</sup>
        <ul>
        <li><b>Explicit</b>: <sup>3</sup> Learn to Play p. 20: &ldquo;Each player may negotiate up to one transaction with each other player while resolving the vote for each agenda.&rdquo;</li>
        </ul></li>
    <li>Planets are readied at the end of the agenda phase; other exhausted cards, such as technologies and agents, stay exhausted.<sup>2</sup>
        <ul>
        <li><b>Implicit</b>: <sup>3</sup> Learn to Play, Ready Planets: &ldquo;Each player readies all of their planet cards.&rdquo;</li>
        </ul></li>
    <li>The Deepwrought player&rsquo;s ocean cards, space stations and <i>The Triad</i> are also readied at the end of the agenda phase.<sup>3,6,7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>3</sup> Learn to Play p. 21, Agenda Phase, &ldquo;3. READY PLANETS&rdquo;: &ldquo;Each player readies all of their planet cards.&rdquo;</li>
        <li><b>Implicit</b>: <sup>3</sup> The Triad card text (not a numbered source): &ldquo;This card can be readied and spent as if it were a planet card.&rdquo; Learn to Play readies all planet cards at the end of the agenda phase, so The Triad is readied then.</li>
        </ul></li>
</ul>
<h2><a href="/R_attacker">Attacker</a></h2>
<ul>
    <li>The attacker&rsquo;s opponent is the defender.<sup>1,3</sup>
        <ul>
        <li><b>Explicit</b>: <sup>3</sup> Learn to Play: &ldquo;During combat, the active player is the attacker and the other player is the defender.&rdquo;</li>
        </ul></li>
</ul>
<h2><a href="/R_bombardment">Bombardment (Unit Ability)</a></h2>
<ul>
    <li>A single planet must be chosen for each unit with the <sc>Bombardment</sc> ability; any hits generated by that unit will be assigned to units on that planet.<sup>1,2,3</sup>
        <ul>
        <li><b>Explicit</b>: <sup>3</sup> Learn to Play: &ldquo;These hits can only be assigned by the bombarded player to ground forces on the planet being bombarded.&rdquo;</li>
        </ul></li>
</ul>
