<header><h1>Twilight Codex Vol. IV: Liberation: Notes</h1></header>
<article>
<p>Every note on this site that <a href="https://cdn.svc.asmodee.net/production-fantasyflightgames/uploads/2026/08/ti_codex_4_rules.pdf" target="_blank" rel="noopener">Twilight Codex Vol. IV: Liberation</a> supports, with the text it is quoted for, grouped by page. <b>Explicit</b> sources state the note directly. <b>Implicit</b> sources support it without stating it.</p>
<h2><a href="/R_gravity_rift">Gravity Rift</a></h2>
<ul>
    <li>Some effects allow ships to move out of or through a gravity rift without rolling for removal, such as the <i>Circlet of the Void</i> relic and the <i>Nav Suite</i> action card.<sup>11</sup>
        <ul>
        <li><b>Explicit</b>: <sup>11</sup> Codex IV, Circlet of the Void: &ldquo;Your units do not roll for gravity rifts, and you ignore the movement effects of other anomalies.&rdquo;</li>
        </ul></li>
</ul>
<h2><a href="/R_nebula">Nebula</a></h2>
<ul>
    <li>The owner of the <i>Circlet of the Void</i> relic ignores the movement effects of nebulae.<sup>11</sup>
        <ul>
        <li><b>Explicit</b>: <sup>11</sup> Codex IV, Circlet of the Void: &ldquo;Your units do not roll for gravity rifts, and you ignore the movement effects of other anomalies.&rdquo;</li>
        </ul></li>
</ul>
<h2><a href="/R_neutral_units">Neutral Units</a></h2>
<ul>
    <li>Neutral units are placed in some systems within The Fracture when it enters play. Several other game effects also place neutral units.<sup>7,11</sup>
        <ul>
        <li><b>Implicit</b>: <sup>11</sup> Codex IV, Minor Factions: &ldquo;that player places 3 neutral infantry on that system&rsquo;s planets.&rdquo;</li>
        </ul></li>
</ul>
<h2><a href="/F_lizix">The L1Z1X Mindnet</a></h2>
<ul>
    <li>Ships do not roll for removal if the L1Z1X player owns the <i>Circlet of the Void</i> relic.<sup>11</sup>
        <ul>
        <li><b>Explicit</b>: <sup>11</sup> Codex IV, Circlet of the Void: &ldquo;Your units do not roll for gravity rifts, and you ignore the movement effects of other anomalies.&rdquo;</li>
        </ul></li>
    <li>Ships may move into a supernova if the L1Z1X player owns the <i>Circlet of the Void</i> relic.<sup>11</sup>
        <ul>
        <li><b>Implicit</b>: <sup>11</sup> Codex IV, Circlet of the Void: &ldquo;Your units do not roll for gravity rifts, and you ignore the movement effects of other anomalies.&rdquo; That includes the supernova&rsquo;s restriction on moving into it.</li>
        </ul></li>
</ul>
