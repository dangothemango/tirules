<header><h1>Prophecy of Kings Rulebook: Notes</h1></header>
<article>
<p>Every note on this site that <a href="https://cdn.svc.asmodee.net/production-fantasyflightgames/uploads/2026/08/ti10_rulebook_web-good.pdf" target="_blank" rel="noopener">Prophecy of Kings Rulebook</a> supports, with the text it is quoted for, grouped by page. <b>Explicit</b> sources state the note directly. <b>Implicit</b> sources support it without stating it.</p>
<h2><a href="/R_capture">Capture</a></h2>
<ul>
    <li>A player cannot capture fighter or infantry tokens corresponding to units belonging to a player that is blockading one of their space docks.<sup>1,8</sup>
        <ul>
        <li><b>Explicit</b>: <sup>8</sup> PoK rulebook p. 10: &ldquo;If at least one of a player&rsquo;s space docks is being blockaded, they cannot capture units from the player who is blockading them.&rdquo;</li>
        </ul></li>
</ul>
<h2><a href="/R_component_limitations">Component Limitations</a></h2>
<ul>
    <li>A player may only resolve a deploy ability to place a unit that is in their reinforcements. A player cannot remove a unit from the board to use its deploy ability.<sup>1,8</sup>
        <ul>
        <li><b>Explicit</b>: <sup>8</sup> PoK rulebook: &ldquo;This ability can be used to place a unit from a player&rsquo;s reinforcements.&rdquo;</li>
        </ul></li>
</ul>
<h2><a href="/R_deploy">Deploy</a></h2>
<ul>
    <li>A player may only resolve a deploy ability to place a unit that is in their reinforcements. A player cannot remove a unit from the board to use its deploy ability.<sup>1,8</sup>
        <ul>
        <li><b>Explicit</b>: <sup>8</sup> PoK rulebook: &ldquo;This ability can be used to place a unit from a player&rsquo;s reinforcements.&rdquo;</li>
        </ul></li>
</ul>
<h2><a href="/R_exploration">Exploration</a></h2>
<ul>
    <li>If a player is to gain multiple planets in a system, they choose the order in which they gain them, and explore each planet as they gain it before gaining the next.<sup>4,8</sup>
        <ul>
        <li><b>Explicit</b>: <sup>8</sup> PoK rulebook p. 11: &ldquo;If a player gains control of multiple planets at the same time, they choose the order in which they explore those planets, drawing and resolving each planet&rsquo;s exploration card before exploring the next planet.&rdquo;</li>
        </ul></li>
</ul>
<h2><a href="/R_frontier_tokens">Frontier Tokens</a></h2>
<ul>
    <li>Players may explore space areas that contain frontier tokens if they own the <i>Dark Energy Tap</i> technology or if another game effect allows them to.<sup>1,8</sup>
        <ul>
        <li><b>Explicit</b>: <sup>8</sup> PoK rulebook p. 16: &ldquo;If an ability instructs a player to explore a frontier token, they may do so even if they do not have the &lsquo;Dark Energy Tap&rsquo; technology.&rdquo;</li>
        </ul></li>
</ul>
<h2><a href="/R_gravity_rift">Gravity Rift</a></h2>
<ul>
    <li>If a ship moves through or out of multiple gravity rifts, each gravity rift provides +1 to its move value and requires a separate roll for removal. If it moves out of the same gravity rift more than once, that gravity rift provides +1 only once, but each instance requires a separate roll.<sup>1,2,6,7,8</sup>
        <ul>
        <li><b>Implicit</b>: <sup>8</sup> PoK rulebook quick reference: the same text.</li>
        </ul></li>
</ul>
<h2><a href="/R_invasion">Invasion</a></h2>
<ul>
    <li>If a player gains control of an uncontrolled planet during the <b>Establish Control</b> step, they explore it.<sup>1,2,8</sup>
        <ul>
        <li><b>Implicit</b>: <sup>8</sup> PoK rulebook quick reference lists &ldquo;Establish Control&rdquo; as the last invasion step.</li>
        </ul></li>
    <li>If a player gains control of a legendary planet, they gain the legendary planet ability card in addition to the planet card.<sup>1,7,8</sup>
        <ul>
        <li><b>Explicit</b>: <sup>8</sup> PoK rulebook p. 10: the same text.</li>
        </ul></li>
</ul>
<h2><a href="/R_pds">PDS</a></h2>
<ul>
    <li>Each PDS also has the <sc>Planetary Shield</sc> ability.<sup>2,3,8</sup>
        <ul>
        <li><b>Explicit</b>: <sup>8</sup> PoK rulebook unit card: &ldquo;PLANETARY SHIELD ✦ SPACE CANNON 6 PDS I.&rdquo;</li>
        </ul></li>
</ul>
<h2><a href="/R_planets">Planets</a></h2>
<ul>
    <li>Planets with traits can be explored.<sup>2,8</sup>
        <ul>
        <li><b>Implicit</b>: <sup>8</sup> PoK rulebook: &ldquo;A planet that does not have a type cannot be explored.&rdquo;</li>
        </ul></li>
</ul>
<h2><a href="/R_space_combat">Space Combat</a></h2>
<ul>
    <li>The <i>Dark Energy Tap</i> technology allows a player to retreat into a system that does not contain their ships or a planet they control.<sup>2,8</sup>
        <ul>
        <li><b>Explicit</b>: <sup>8</sup> PoK rulebook, Dark Energy Tap: &ldquo;Your ships can retreat into adjacent systems that do not contain other players&rsquo; units, even if you do not have units or control planets in that system.&rdquo;</li>
        </ul></li>
</ul>
<h2><a href="/R_transactions">Transactions</a></h2>
<ul>
    <li>Relic fragments may be traded. Relics themselves cannot be.<sup>1,8</sup>
        <ul>
        <li><b>Explicit</b>: <sup>8</sup> PoK rulebook, Relics: &ldquo;Relics cannot be exchanged as part of a transaction even though relic fragments can be exchanged.&rdquo;</li>
        </ul></li>
    <li>Captured non&ndash;fighter ships and mechs may be returned to the player that originally owned them as part of a transaction.<sup>1,8</sup>
        <ul>
        <li><b>Explicit</b>: <sup>8</sup> PoK rulebook p. 10: &ldquo;A captured non-fighter ship or mech can be returned, as follows: ✦ If the player who captured the unit agrees&rdquo; as part of a transaction.</li>
        </ul></li>
</ul>
<h2><a href="/F_argent">The Argent Flight</a></h2>
<ul>
    <li>The <sc>Anti&ndash;Fighter Barrage</sc> ability can still be used even if no fighters are present in the system.<sup>1,2,8</sup>
        <ul>
        <li><b>Explicit</b>: <sup>8</sup> PoK rulebook p. 16: &ldquo;The &lsquo;Anti-Fighter Barrage&rsquo; step can occur even if a player&rsquo;s opponent has no fighters in the combat.&rdquo;</li>
