<ul>
    <li>(Thunder&rsquo;s Edge) Entropic scars are a fifth type of anomaly.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 11: &ldquo;An entropic scar is a new kind of anomaly.&rdquo;</li>
        </ul></li>
