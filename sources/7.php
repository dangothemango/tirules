<h2><a href="/R_blockaded">Blockaded</a></h2>
<ul>
    <li>(Thunder&rsquo;s Edge) Coexisting units are always blockaded, so they can produce ground forces but cannot produce ships.<sup>7,9</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 11, Coexist: &ldquo;Coexisting structures are always blockaded.&rdquo;</li>
        </ul></li>
</ul>
<h2><a href="/R_bombardment">Bombardment (Unit Ability)</a></h2>
<ul>
    <li>(Thunder&rsquo;s Edge) If a player makes a bombardment roll against a planet that contains coexisting units, that player chooses which units with <sc>Bombardment</sc> are bombarding which other player&rsquo;s units, and rolls against each player separately.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 11, Coexist: &ldquo;Coexisting units can be bombarded. When a player makes a bombardment roll against a planet, they choose which of their units with bombardment are bombarding which other player&rsquo;s units, rolling against each player separately.&rdquo;</li>
        </ul></li>
</ul>
<h2><a href="/R_breakthroughs">Breakthroughs</a></h2>
<ul>
    <li>A breakthrough is a faction specific card.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 4: &ldquo;unlock powerful new abilities via faction-specific breakthroughs.&rdquo;</li>
        </ul></li>
    <li>A breakthrough is commonly gained through an expedition. There are other game effects that can gain a player their faction&rsquo;s breakthrough.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 8: &ldquo;The first time a player claims one of the expedition slices, they gain their faction&rsquo;s breakthrough.&rdquo;</li>
        </ul></li>
    <li>When a player gains their faction&rsquo;s breakthrough, they perform a breakthrough roll, which may cause The Fracture to enter play.<sup>2,7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 5: &ldquo;Roll a die on gaining breakthrough; on a roll of 1 or 10, that player puts The Fracture into play.&rdquo;</li>
        </ul></li>
    <li>A breakthrough has 1 or more abilities, and a synergy (other than for the <a href="/F_nekro">Nekro</a> player).<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 9: &ldquo;a breakthrough that does not have synergy (as is the case with the Nekro Virus faction).&rdquo;</li>
        </ul></li>
</ul>
<h2><a href="/R_coexistence">Coexistence</a></h2>
<ul>
    <li>Some game effects allow two or more players&rsquo; units to exist on a planet without triggering combat; this is coexistence.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 11, Coexist: &ldquo;Some game effects allow a player&rsquo;s units to coexist with other units on a planet. When a unit or units coexist with another player&rsquo;s units, they do not trigger combat.&rdquo;</li>
        </ul></li>
    <li>One player controls the planet; all other players are coexisting on that planet.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 11, Coexist: &ldquo;The player whose units triggered coexistence does not gain or retain control of the planet.&rdquo;</li>
        </ul></li>
    <li>If a game effect instructs a player to coexist on a planet they do not control, the original controller of that planet retains control.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 11, Coexist: &ldquo;The player whose units triggered coexistence does not gain or retain control of the planet.&rdquo;</li>
        </ul></li>
    <li>If a game effect instructs a player to coexist on a planet they do control, then another player will gain control of that planet (which will exhaust that planet).<sup>2,7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 11, Coexist: &ldquo;if they already controlled it, the player they are now coexisting with gains control of it instead, exhausted.&rdquo;</li>
        </ul></li>
    <li>If additional units are added to those already coexisting, by, for example, committing additional ground forces during an invasion, or resolving an effect that allows a unit to be placed directly on a planet, the added units immediately coexist.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 11, Coexist: &ldquo;If the coexisting player places, produces, or moves additional units onto that planet, those units also coexist.&rdquo;</li>
        </ul></li>
    <li>If only one player has units on a planet that was in coexistence, and that player was coexisting, they gain control of that planet.<sup>6,7,9</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 11, Coexist: &ldquo;If a player&rsquo;s coexisting units become the only units on a planet, that player gains control of the planet.&rdquo;</li>
        </ul></li>
    <li>All coexisting units are blockaded, regardless of what ships, if any, are in the system. This includes units that are not structures, such as mechs with the <sc>Production</sc> ability.<sup>2,6,7,9</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 11, Coexist: &ldquo;Coexisting structures are always blockaded.&rdquo;</li>
        </ul></li>
    <li>When a player uses the <sc>Bombardment</sc> ability of 1 of their units against a planet in coexistence, they choose which player&rsquo;s units on that planet will have the hits assigned.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 11, Coexist: &ldquo;When a player makes a bombardment roll against a planet, they choose which of their units with bombardment are bombarding which other player&rsquo;s units, rolling against each player separately.&rdquo;</li>
        </ul></li>
    <li>If that player has multiple units with the <sc>Bombardment</sc> ability, they make this choice independently for each unit.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 11, Coexist: &ldquo;they choose which of their units with bombardment are bombarding which other player&rsquo;s units.&rdquo;</li>
        </ul></li>
    <li>If that player produces a surplus of hits above the number of units of the player they have chosen, the extra hits cannot be assigned to the units of a different player on that planet.<sup>7</sup>
        <ul>
        <li><b>Implicit</b>: <sup>7</sup> Same passage: &ldquo;rolling against each player separately.&rdquo;</li>
        </ul></li>
    <li>A player who controls a planet may start a ground combat against a coexisting player during the invasion step of a tactical action.<sup>6,7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 11, Coexist: &ldquo;Coexisting units can have combat initiated against them by units being committed to the planet that contains them, including units that they were already coexisting with.&rdquo;</li>
        </ul></li>
    <li>A player who is coexisting on a planet may start a ground combat against the player that controls that planet during the invasion step of a tactical action.<sup>2,7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 11, Coexist: &ldquo;a coexisting player may choose to end their coexistence by activating the coexisting unit&rsquo;s system and committing the coexisting units against the planet they are coexisting on.&rdquo;</li>
        </ul></li>
    <li>A player who had no units on a planet, but commits 1 or more ground forces during the invasion step of a tactical action must start a ground combat against the player that controls that planet (unless they have an ability that would allow them to coexist).<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 11, Coexist: &ldquo;When a unit or units coexist with another player&rsquo;s units, they do not trigger combat.&rdquo; Only units with a coexist effect avoid combat.</li>
        </ul></li>
    <li>Should a player win the ground combat on a planet resulting from one of these aforementioned methods, they gain control of that planet, if they were not in control of it already. Then, they may start an additional ground combat against another coexisting player, if present, and may continue to do so until they decline to start another ground combat or there are no more coexisting players. Any coexisting players that they do not resolve a ground combat against remain coexisting.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 11, Coexist: &ldquo;If a player does wish to engage coexisting units, they may optionally engage a coexisting player&rsquo;s units after winning a combat against the planet&rsquo;s owner, initiating separate combats against any coexisting player as desired.&rdquo;</li>
        </ul></li>
    <li>When scoring an objective, a coexisting player considers both themselves and the controlling player to control that planet. The player that controls the planet does not count a coexisting player as also controlling it.<sup>2,6,7,9</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 11, Coexist: &ldquo;When scoring objectives&rdquo; a coexisting player counts as controlling the planet.</li>
        </ul></li>
</ul>
<h2><a href="/R_commodities">Commodities</a></h2>
<ul>
    <li>For each space station a player controls, their commodity value is increased by one.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 10: &ldquo;A player&rsquo;s commodity value is increased by 1 for each space station they control.&rdquo;</li>
        </ul></li>
    <li>A player may exhaust a space station at any time to convert any commodities that they have into trade goods.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 10: &ldquo;players can exhaust a space station&rdquo; to convert commodities to trade goods.</li>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge reference: &ldquo;Exhaust to convert commodities to trade goods.&rdquo;</li>
        </ul></li>
</ul>
<h2><a href="/R_control">Control</a></h2>
<ul>
    <li>(Thunder&rsquo;s Edge) The player whose units trigger coexistence on a planet does not gain or retain control of it; if they already controlled it, the player they now coexist with gains control of it, exhausted. If a player&rsquo;s coexisting units become the only units on a planet, that player gains control of it.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 11, Coexist: &ldquo;The player whose units triggered coexistence does not gain or retain control of the planet; if they already controlled it, the player they are now coexisting with gains control of it instead, exhausted. &hellip; If a player&rsquo;s coexisting units become the only units on a planet, that player gains control of the planet.&rdquo;</li>
        </ul></li>
</ul>
<h2><a href="/R_diplomacy">Diplomacy (Strategy Card)</a></h2>
<ul>
    <li>The Diplomacy token represents a command token from each player other than the player with the <i>Diplomacy</i> strategy card. It may be used to simplify play when no player is expected to interact with the command tokens placed by the primary ability.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 12, Diplomacy Token: &ldquo;This token is a player aid included to facilitate ease of play when resolving simple uses of the &lsquo;Diplomacy&rsquo; strategy card&rsquo;s primary ability. It represents a command token from each player.&rdquo;</li>
        </ul></li>
    <li>A player cannot increase the number of tokens they have access to from the use of the Diplomacy token.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Same passage: &ldquo;It cannot be used to bring a player above the component limit for command tokens.&rdquo;</li>
        </ul></li>
    <li>Game effects that can remove a command token from a system may still be used to remove a command token from the system containing the Diplomacy token. Should this happen, players may first wish to replace the Diplomacy token with the corresponding command tokens, then remove the required command token, leaving the rest in the system.<sup>2,7</sup>
        <ul>
        <li><b>Implicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook, Diplomacy Token: &ldquo;should not be used when interacting with abilities that remove command tokens.&rdquo; such abilities handled without the token.</li>
        </ul></li>
    <li>The system that contains the Diplomacy token should be treated as containing a command token of the relevant players for all game effects.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 12: &ldquo;It represents a command token from each player.&rdquo;</li>
        </ul></li>
</ul>
<h2><a href="/R_entropic_scars">Entropic Scars</a></h2>
<ul>
    <li>An entropic scar is an anomaly that affects unit abilities and faction technologies.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge reference: &ldquo;ENTROPIC SCAR (ANOMALY) ✦ UNIT ABILITIES cannot be used by or against units inside of an entropic scar.&rdquo;</li>
        </ul></li>
    <li>A unit in an entropic scar cannot use unit abilities.<sup>2,7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 11, Entropic Scar: &ldquo;(Sustain Damage, Production, Planetary Shield, Space Cannon, Bombardment, Deploy, and Anti-Fighter Barrage) cannot be used by or against units inside of an entropic scar.&rdquo;</li>
        </ul></li>
    <li>Only unit abilities cannot be used; text abilities are unaffected.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 11, Entropic Scar: &ldquo;All unit abilities ... cannot be used by or against units inside of an entropic scar. Text abilities are unaffected.&rdquo;</li>
        </ul></li>
    <li>A unit outside of an entropic scar cannot use unit abilities against units that are in an entropic scar.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 11, Entropic Scar: unit abilities &ldquo;cannot be used by or against units inside of an entropic scar.&rdquo;</li>
        </ul></li>
    <li>Wormhole tokens that would be placed in an entropic scar are discarded instead.<sup>6,7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 11, Entropic Scar: &ldquo;wormholes that would be placed inside of an entropic scar are discarded instead.&rdquo;</li>
        </ul></li>
    <li>At the start of the status phase, a player with ships in an entropic scar may spend a command token from their strategy pool to gain one of their faction&ndash;specific technologies.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 11, Entropic Scar: &ldquo;At the start of the status phase, a player that has ships in an entropic scar can spend a token from their strategy pool to gain one of their faction-specific technologies.&rdquo;</li>
        </ul></li>
</ul>
<h2><a href="/R_exhausted">Exhausted</a></h2>
<ul>
    <li>This includes the Deepwrought player&rsquo;s <a href="/F_deepwrought">ocean cards</a>, space stations and <i>The Triad</i>.<sup>3,6,7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 10: &ldquo;Each space station has a corresponding planet card, which is gained exhausted and is spent, readied as if it were a planet.&rdquo;</li>
        </ul></li>
</ul>
<h2><a href="/R_expedition">Expeditions</a></h2>
<ul>
    <li>A player may perform an expedition, which will unlock their breakthrough, and potentially put The Fracture and/or <a href="https://twilight-imperium.fandom.com/wiki/Thunder&#x27;s_Edge">Thunder&rsquo;s Edge</a> into play.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 4: &ldquo;Its additional game systems take players through the Thunder&rsquo;s Edge expedition, unlock powerful new abilities via faction-specific breakthroughs.&rdquo;</li>
        </ul></li>
    <li>At the end of their turn, a player may perform an expedition. To do so they choose one of the unclaimed slices on the expedition token. They pay the indicated cost, and place one of their control tokens in the indicated area to claim it.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 8: &ldquo;At the end of a player&rsquo;s turn, they may commit to the expedition. To do so, they choose an unclaimed slice of the expedition and pay the indicated cost, placing one of their control tokens in that slice.&rdquo;</li>
        </ul></li>
    <li>When a player performs an expedition, they gain their faction&rsquo;s breakthrough if they do not already have it. This will trigger a breakthrough roll to possibly place The Fracture into play.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 8: &ldquo;The first time a player claims one of the expedition slices, they gain their faction&rsquo;s breakthrough.&rdquo; And: &ldquo;When a player gains their breakthrough, regardless of the source, if The Fracture is not already in play,&rdquo; they roll.</li>
        </ul></li>
    <li>The costs to perform an expedition are:<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 8: &ldquo;The expedition costs are as follows: Spend 5 Resources Discard 2 Action Cards Spend 5 Influence Discard 1 Unscored Secret Objective Exhaust 1 Technology Specialty Planet Spend 3 Trade Goods.&rdquo;</li>
        </ul></li>
    <li>Spend five resources;<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 8: &ldquo;Spend 5 Resources.&rdquo;</li>
        </ul></li>
    <li>Discard two action cards;<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 8: &ldquo;Discard 2 Action Cards.&rdquo;</li>
        </ul></li>
    <li>Spend five influence;<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 8: &ldquo;Spend 5 Influence.&rdquo;</li>
        </ul></li>
    <li>Discard one unscored secret objective;<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 8: &ldquo;Discard 1 Unscored Secret Objective.&rdquo;</li>
        </ul></li>
    <li>Exhaust a planet that has a technology specialty; or<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 8: &ldquo;Exhaust 1 Technology Specialty Planet.&rdquo;</li>
        </ul></li>
    <li>Spend three trade goods.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 8: &ldquo;Spend 3 Trade Goods.&rdquo;</li>
        </ul></li>
    <li>One player may claim multiple slices. A single slice cannot be claimed multiple times (neither by the same or different players).<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 8: &ldquo;Once claimed, that slice cannot be claimed by another player &hellip; A player can claim multiple expedition slices in a game, but must choose a different unclaimed slice each time they do so.&rdquo;</li>
        </ul></li>
    <li>A player may claim only one slice at the end of each of their turns.<sup>7</sup>
        <ul>
        <li><b>Implicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 8: &ldquo;At the end of a player&rsquo;s turn, they may commit to the expedition. To do so, they choose an unclaimed slice of the expedition and pay the indicated cost.&rdquo; And: &ldquo;A player can claim multiple expedition slices in a game, but must choose a different unclaimed slice each time they do so.&rdquo; One slice is chosen each time a player commits at the end of their turn.</li>
        </ul></li>
    <li>If a player already has their breakthrough when they claim a slice, no additional effect will trigger.<sup>7</sup>
        <ul>
        <li><b>Implicit</b>: <sup>7</sup> Same passage: &ldquo;The first time a player claims one of the expedition slices, they gain their faction&rsquo;s breakthrough.&rdquo;</li>
        </ul></li>
    <li>Once the sixth and final slice has been claimed, Thunder&rsquo;s Edge will enter play.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 8: &ldquo;When all slices are claimed, the expedition is complete.&rdquo;</li>
        </ul></li>
    <li>The player who claimed the sixth and final slice flips the expedition token to the Thunder&rsquo;s Edge side, and places it in a system on the game board. They must choose a system that does not contain a planet, a supernova, or a printed wormhole, and is not in The Fracture, should it be in play.<sup>2,6,7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 8: &ldquo;the player who claimed the final slice flips Thunder&rsquo;s Edge to its planet side and places it in a system of their choice that does not contain a planet, a supernova, or a printed wormhole.&rdquo;</li>
        </ul></li>
    <li>Finally, the player who had claimed the most slices of the expedition token places a number of infantry equal to the number of slices they had claimed on to Thunder&rsquo;s Edge. If multiple players are tied for the most number of slices, the player placing Thunder&rsquo;s Edge chooses one of those players to place the infantry; they may choose themself.<sup>2,7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 8: &ldquo;the player with the most control tokens on the expedition places that many infantry on Thunder&rsquo;s Edge. In the case of a tie, the player who claimed the final slice chooses which tied player&rdquo; places them.</li>
        </ul></li>
    <li>If Thunder&rsquo;s Edge is placed in a system containing a frontier token, that token is not removed.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 16: &ldquo;When Thunder&rsquo;s Edge is placed into a system that contains a frontier token, do not remove the frontier token; it can still be explored.&rdquo;</li>
        </ul></li>
</ul>
<h2><a href="/R_fracture">The Fracture</a></h2>
<ul>
    <li>The Fracture consists of additional systems beyond the regular bounds of the game map.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 9, The Fracture: &ldquo;The Fracture is an enigmatic area of space that is not connected to the rest of the galaxy.&rdquo;</li>
        </ul></li>
    <li>When a player gains their breakthrough, they roll a die. On a result of 1 or 10, The Fracture enters play. Other game effects may also bring The Fracture into play.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge reference: &ldquo;Roll a die on gaining breakthrough; on a roll of 1 or 10, that player puts The Fracture into play.&rdquo;</li>
        <li><b>Implicit</b>: <sup>7</sup> p. 9 mentions Fracture &ldquo;brought into play by another ability.&rdquo;</li>
        </ul></li>
    <li>When The Fracture enters play, it is placed against the edge of the regular game map.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 9, The Fracture: &ldquo;the player that brought it into play places it along any edge of the game board, based on player count.&rdquo;</li>
        </ul></li>
    <li>The placement location of The Fracture is arbitrary, and should have no mechanical effect on the game state.<sup>2,7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 9, The Fracture: &ldquo;Regardless of where The Fracture is placed, its systems are not adjacent to the systems it is touching.&rdquo;</li>
        </ul></li>
