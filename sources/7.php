        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 10: &ldquo;Each space station has a corresponding planet card, which is gained exhausted and is spent, readied as if it were a planet.&rdquo;</li>
        </ul></li>
</ul>
