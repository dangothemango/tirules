        <li><b>Explicit</b>: <sup>5</sup> Designer ruling (Dane, via Skootur, Oct 19, 2017): &ldquo;&mdash;Binding: Give me two trade goods and I&rsquo;ll let you refresh your commodities without spending a command token.&rdquo;</li>
        </ul></li>
</ul>
<h2><a href="/R_fleet_pool">Fleet Pool</a></h2>
<ul>
    <li>Fighters and ground forces do not count toward capacity during combat. When combat ends however, units will need to be removed to meet capacity requirements.<sup>1,2,3,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>5</sup> Designer ruling: &ldquo;During a combat, the fighters would persist until the end of combat.&rdquo;</li>
        </ul></li>
    <li>Ships may be moved into or produced in a system even if doing so would exceed the fleet pool limit. However, some of those ships must immediately be removed to satisfy the limit.<sup>2,5,6</sup>
        <ul>
        <li><b>Explicit</b>: <sup>5</sup> Designer ruling: &ldquo;Once all ships are in, fleet supply is in violation and must immediately be dealt with.&rdquo;</li>
        </ul></li>
    <li>During movement, a ship may move through a system regardless of how many ships are in that system relative to the fleet pool limit.<sup>2,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>5</sup> Designer ruling (Bocks, Mar 17, 2018): &ldquo;In neither instance do you need to destroy any ships due to fleet supply&rdquo;</li>
        </ul></li>
</ul>
<h2><a href="/R_infantry_tokens">Infantry Tokens</a></h2>
<ul>
    <li>A player may remove a plastic infantry figure from a planet or space area, along with any accompanying infantry tokens, if doing so allows them to swap it into the active system and allows them to commit ground forces to and fight ground combats on multiple planets during the <b>Invasion</b> step of the tactical action in that system when they could otherwise not do so.<sup>2,5</sup>
        <ul>
        <li><b>Implicit</b>: <sup>5</sup> Designer ruling (Yin4Life, Apr 22, 2019), on placing ground forces on a 13th planet: &ldquo;You place the units one at a time, so when you place on the 13th planet, you&rsquo;d have to remove a plastic ground force from somewhere that you already placed one.&rdquo; Covers placing, not committing.</li>
        </ul></li>
</ul>
<h2><a href="/R_initiative_order">Initiative Order</a></h2>
<ul>
    <li>If there are multiple abilities that players wish to resolve at the same time during the action phase, initiative order will determine the order they are resolved in. See the <a href="/R_abilities">abilities page</a> for more details.<sup>1,2,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>5</sup> Designer ruling (kaiteinomen, Sep 20, 2017): &ldquo;All timing conflicts are intended to follow the same rules for resolution&mdash;in initiative order, beginning with the active player.&rdquo;</li>
        </ul></li>
</ul>
<h2><a href="/R_movement">Movement</a></h2>
<ul>
    <li>During a retreat, units may be transported from the active system.<sup>5,10</sup>
        <ul>
        <li><b>Explicit</b>: <sup>5</sup> Designer ruling (x3n d0g, 07/18/2018): &ldquo;When retreating, you are only allowed to take the ground forces if you pick them up during the announce retreat step.&rdquo;</li>
        </ul></li>
    <li>A ship that can both move and be transported (i.e. Fighter II) cannot do both by &ldquo;meeting&rdquo; a ship with capacity partway through a tactical action movement, as all movement is simultaneous.<sup>1,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>5</sup> FFG answer: &ldquo;the fighters&rsquo; movement is not legal. Because there is no partial movement, the Advanced Fighters can either reach the active system from their current system or they cannot. It is not possible to move them part of the way and have a carrier do the rest of the work.&rdquo;</li>
        </ul></li>
    <li>Fighters alone will block other players&rsquo; ships from moving through that system, whether they are accompanied by a Space Dock or they are Fighters II.<sup>1,2,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>5</sup> Designer ruling: &ldquo;Lone advanced fighters can block other players&rsquo; ship movement.&rdquo;</li>
        </ul></li>
</ul>
<h2><a href="/R_neighbors">Neighbors</a></h2>
<ul>
    <li>A player may resolve one transaction with each other player per each agenda during the agenda phase, however, the agenda phase does not make all players neighbors.<sup>1,2,3,5</sup>
        <ul>
        <li><b>Implicit</b>: <sup>5</sup> Designer ruling (x3n d0g, 01/17/2019): &ldquo;Simply being in the agenda phase does not confer neighbor status to all players.&rdquo; Neighbor clause stated; transaction-per-agenda limit only loosely supported (agenda phase transactions are free, new transactions allowed per new agenda).</li>
        </ul></li>
</ul>
<h2><a href="/R_objective_cards">Objective Cards</a></h2>
<ul>
    <li>The <b>Anti&ndash;Fighter Barrage</b> step, however, is a step during combat.<sup>1,2,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>5</sup> Designer ruling (livestrongbelwas, Feb 08, 2018): &ldquo;Anti-Fighter Barrage, which is its own distinct timing (essentially the first step of combat)&rdquo;</li>
        </ul></li>
    <li>A player may choose to reveal any or all of their unscored secret objectives to other players.<sup>1,2,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>5</sup> Designer ruling (x3n d0g, 1/25/2019): &ldquo;If you feel you have a reason to show someone a card, perhaps as part ot a negotiation or to convince them to do something for you, that is your prerogative and I would prefer not to restrict that.&rdquo;</li>
        </ul></li>
</ul>
<h2><a href="/R_production">Production (Unit Ability)</a></h2>
<ul>
    <li>Placement of produced units is not limited by a unit&rsquo;s <sc>Production</sc> value, only by the location of the producing units.<sup>1,2,5</sup>
        <ul>
        <li><b>Implicit</b>: <sup>5</sup> Designer ruling (kaiteinomen, Sep 28, 2017): &ldquo;you can put both of the Letani warriors on the same planet, if you wish, as long as one of the units that used Production is located there.&rdquo; Only location of producing unit matters for placement.</li>
        </ul></li>
</ul>
<h2><a href="/R_promissory_notes">Promissory Notes</a></h2>
<ul>
    <li>If a player receives a card, such as a promissory note, in a transaction during that card&rsquo;s timing window, they may play it immediately. For example, a promissory note with &ldquo;At the start of your turn:&rdquo; timing may be played immediately if the transaction occurred during the &ldquo;start of turn&rdquo; timing window.<sup>1,2,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>5</sup> Designer ruling: &ldquo;You can trade a promissory note and have it be immediately used during the start of turn window.&rdquo;</li>
        </ul></li>
</ul>
<h2><a href="/R_space_cannon">Space Cannon (Unit Ability)</a></h2>
<ul>
    <li>A player cannot assign hits produced by a space cannon roll to their own units.<sup>2,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>5</sup> Designer ruling (x3n d0g, 09/10/2018): &ldquo;You cannot use a PDS to target your own ships.&rdquo;</li>
        </ul></li>
</ul>
<h2><a href="/R_space_combat">Space Combat</a></h2>
<ul>
    <li>Abilities that resolve at the start of a space combat, such as the <i>Assault Cannon</i> technology and the <a href="/F_mentak">Mentak</a> player&rsquo;s <a href="https://twilight-imperium.fandom.com/wiki/The_Mentak_Coalition#Faction_Abilities:~:text=Ambush"><sc>Ambush</sc></a> faction ability, are resolved before the <b>Anti&ndash;Fighter Barrage</b> step.<sup>2,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>5</sup> Designer ruling: &ldquo;Assault Cannon and Mentak&rsquo;s Ambush happen before Anti-Fighter Barrage, which is its own distinct timing (essentially the first step of combat).&rdquo;</li>
        </ul></li>
    <li>A player&rsquo;s fighters and ground forces do not count against capacity during combat. At the end of combat, any excess units are removed and returned to that player&rsquo;s reinforcements.<sup>1,2,5</sup>
        <ul>
        <li><b>Implicit</b>: <sup>5</sup> Designer ruling (Milty, 08/02/2018): &ldquo;During a combat, the fighters would persist until the end of combat&rdquo; Fighters persist through combat despite capacity.</li>
        </ul></li>
    <li>While retreating, a player cannot transport more fighters and/or ground forces than they have capacity in the retreating ships.<sup>1,2,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>5</sup> Designer ruling: &ldquo;the number you can attempt to move out of the system is still limited by your ships capacity in the same way that it is when you move.&rdquo;</li>
        </ul></li>
    <li>When a player retreats, their fighters that remain in the space area of the active system are removed, even if that system contains one of their space docks.<sup>2,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>5</sup> Designer ruling (sigmazero13, Jul 18, 2018): &ldquo;They&rsquo;d be destroyed.&rdquo;</li>
        </ul></li>
</ul>
<h2><a href="/R_space_dock">Space Dock</a></h2>
<ul>
    <li>Fighters transported during movement remain assigned to the transporting ship until movement is complete. They cannot be counted toward a space dock&rsquo;s allocation until after movement is complete.<sup>1,2,5</sup>
        <ul>
        <li><b>Implicit</b>: <sup>5</sup> Designer ruling (sigmazero13, Aug 24, 2018): &ldquo;The intent is that the units are dropped off after the ship has ended its movement in the active system.&rdquo; Units stay aboard until movement ends.</li>
        </ul></li>
</ul>
<h2><a href="/R_speaker">Speaker</a></h2>
<ul>
    <li>During the strategy and agenda phases, the speaker will have the first opportunity to resolve abilities during each timing window.<sup>1,2,5</sup>
        <ul>
        <li><b>Implicit</b>: <sup>5</sup> Designer ruling (alercah, Nov 22, 2017): &ldquo;The intended tiebreaker when there is no initiative order is the one you mentioned: speaker, then clockwise.&rdquo; Speaker acts first when there is no initiative order.</li>
        </ul></li>
</ul>
<h2><a href="/R_strategy_phase">Strategy Phase</a></h2>
<ul>
    <li>If a player chooses a strategy card, but later loses it, they will keep any trade goods that were on the strategy card.<sup>5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>5</sup> Designer ruling: &ldquo;In both the situations you mentioned there (Quantum Datahub Node and Acquiescence) the player who picked the strategy card originally would get the trade goods.&rdquo;</li>
        </ul></li>
</ul>
<h2><a href="/R_supernova">Supernova</a></h2>
<ul>
    <li>If a ship finds itself in a supernova by some uncommon game effect, it may remain there without harm.<sup>2,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>5</sup> Designer ruling: &ldquo;the effects of a supernova do not kill ships, only restrict or disallow movement.&rdquo;</li>
        </ul></li>
</ul>
<h2><a href="/R_sustain_damage">Sustain Damage</a></h2>
<ul>
    <li>If multiple ships use their <sc>Sustain Damage</sc> ability, a <i>Direct Hit</i> action card may be played for each.<sup>1,2,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>5</sup> Designer ruling: &ldquo;Because the Direct Hits are targeting different ships/instances of sustain damage use, this is allowed.&rdquo;</li>
        </ul></li>
</ul>
