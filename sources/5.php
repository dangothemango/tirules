<h2><a href="/R_abilities">Abilities</a></h2>
<ul>
    <li>An ability may be triggered during the timing window it was gained, if applicable. For example, if a player receives the <a href="/F_creuss">Creuss</a> player&rsquo;s <a href="https://twilight-imperium.fandom.com/wiki/The_Ghosts_of_Creuss#Faction_Promissory_Note:~:text=Creuss%20Iff"><i>Creuss Iff</i></a> promissory note at the start of their turn, they may use it immediately.<sup>1,2,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>5</sup> Designer ruling: &ldquo;You can trade a promissory note and have it be immediately used during the start of turn window. That is allowed.&rdquo;</li>
        </ul></li>
    <li>The <i>Assault Cannon</i> technology is an example of an ability that checks its condition when it would resolve; a player without three or more non&ndash;fighter ships in the system cannot use <i>Assault Cannon</i>, even if they previously had more ships.<sup>2,5</sup>
        <ul>
        <li><b>Implicit</b>: <sup>5</sup> Designer ruling (livestrongbelwas, Feb 08, 2018): &ldquo;The second player doesn&rsquo;t get to use his Assault Cannons&rdquo; Condition is checked when the ability would resolve.</li>
        </ul></li>
    <li>An ability from a single physical object cannot be resolved more than once in one timing window. For example, if a player starts their turn with the Creuss player&rsquo;s <i>Creuss Iff</i> promissory note in their hand (having received it on a previous turn) and uses it, they will not be able to use it a second time this turn, if they receive it again as part of a transaction.<sup>1,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>5</sup> Designer ruling: &ldquo;because of rule 1.16, that PN cannot be traded and resolved multiple times during the same window.&rdquo;</li>
        </ul></li>
    <li>During the action phase, abilities are resolved in the current relative turn order, starting with the active player. For example, if it is currently the <i>Trade</i> (5) player&rsquo;s turn, they will have the option to resolve first, then the <i>Warfare</i> (6) player, then the <i>Technology</i> (7) player, and so on.<sup>1,2,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>5</sup> Designer ruling (kaiteinomen, Sep 20, 2017): &ldquo;The order would be 5, 6, 7, 1, 2, 3, as you suggested.&rdquo;</li>
        </ul></li>
    <li>If a player has multiple abilities they wish to resolve, they must be resolved one at a time. Between each ability being resolved, each other player will have the opportunity to resolve one ability.<sup>1,2,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>5</sup> Designer ruling: &ldquo;You keep going around the circle/sequence until everybody passes simultaneously. &hellip; Dane: Regarding your question, option 2 is the intended method of resolution.&rdquo;</li>
        </ul></li>
    <li>Once every player has consecutively declined to resolve an ability during a timing window, no more abilities may be resolved during that window.<sup>2,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>5</sup> Designer ruling: &ldquo;You keep going around the circle/sequence until everybody passes simultaneously. &hellip; Dane: Regarding your question, option 2 is the intended method of resolution.&rdquo;</li>
        </ul></li>
    <li>A player may decline to resolve an ability during a timing window, but later choose to resolve an ability during that same timing window, but only if another player chooses to resolve an ability after the player declined.<sup>2,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>5</sup> The same designer ruling rejects the alternative, &ldquo;If a player chooses not to activate an ability, then they won&rsquo;t be activating any more abilities in that timing window,&rdquo; in favor of continuing &ldquo;until everybody passes.&rdquo;</li>
        </ul></li>
</ul>
<h2><a href="/R_action_cards">Action Cards</a></h2>
<ul>
    <li>A player may choose to reveal any or all of the action cards in their hand.<sup>1,2,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>5</sup> Designer ruling (sigmazero13, Jan 16, 2018): &ldquo;There are no rules preventing players from showing an an action card from their hand.&rdquo;</li>
        </ul></li>
    <li>If a player&rsquo;s action card is canceled, usually via a <i>Sabotage</i> action card, then if that player has a second copy of that action card, they may play it.<sup>2,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>5</sup> Designer ruling: &ldquo;Because the card was cancelled, yes, you can play another copy of the same action card.&rdquo;</li>
        </ul></li>
    <li>A player cannot use action cards that destroy units, such as <i>Lucky Shot</i>, against their own units.<sup>1,2,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>5</sup> Designer ruling (Yin4Life, 12/10/2018): &ldquo;No, You cannot use Lucky Shot to target one of your own ships.&rdquo;</li>
        </ul></li>
    <li>If an action card targets a specific number of a particular type of object, that action card cannot be played if those objects do not currently exist. For example, <i>Repeal Law</i> cannot be played if there are no laws in play.<sup>5</sup>
        <ul>
        <li><b>Implicit</b>: <sup>5</sup> Designer ruling (x3n d0g, 1/25/2019): &ldquo;think Repeal Law when there are no laws in play&rdquo; Repeal Law is the cited example of a card with no legal target that cannot be played.</li>
        </ul></li>
    <li>Action cards are discarded faceup. Players may look through the action card discard pile.<sup>2,4,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>5</sup> Designer ruling: &ldquo;Action cards are discarded faceup and players may look through the discard deck.&rdquo;</li>
        </ul></li>
</ul>
<h2><a href="/R_active_player">Active Player</a></h2>
<ul>
    <li>The active player will have the first opportunity to resolve abilities during each timing window.<sup>1,2,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>5</sup> Designer ruling (kaiteinomen, Sep 20, 2017): &ldquo;All timing conflicts are intended to follow the same rules for resolution&mdash;in initiative order, beginning with the active player.&rdquo;</li>
        </ul></li>
</ul>
<h2><a href="/R_agenda_phase">Agenda Phase</a></h2>
<ul>
    <li>Casting zero votes for an outcome is the same as abstaining. A player that casts zero votes gains no positive or negative effects of voting for that outcome.<sup>1,2,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>5</sup> Designer ruling: &ldquo;Consider zero votes to be mechanically the same as abstaining.&rdquo;</li>
        </ul></li>
</ul>
<h2><a href="/R_capacity">Capacity (Attribute)</a></h2>
<ul>
    <li>Capacity limits are checked immediately whenever a combat is not in progress.<sup>2,5</sup>
        <ul>
        <li><b>Implicit</b>: <sup>5</sup> Designer ruling (Milty, 08/02/2018): &ldquo;During a combat, the fighters would persist until the end of combat, but in this case they are immediately destroyed.&rdquo; Capacity enforced immediately after a Space Cannon Offense hit, outside combat.</li>
        </ul></li>
    <li>If a ship with capacity is destroyed during the <b>Space Cannon Offense</b> step, its player removes the excess units immediately, after that player&rsquo;s hits are assigned and before the next player rolls. The excess units do not remain until space combat.<sup>2,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>5</sup> Designer ruling (Milty, 08/02/2018): &ldquo;During a combat, the fighters would persist until the end of combat, but in this case they are immediately destroyed.&rdquo;</li>
        </ul></li>
    <li>A ship cannot pick up more units from a planet than it has capacity. However, a ship may pick up any units (including zero) in a system as it transports, even if doing so would cause units to be removed due to capacity limits.<sup>2,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>5</sup> Designer ruling: &ldquo;No, you cannot exceed a unit&rsquo;s capacity to intentionally destroy units. You would have to leave some of them on the planet in this case.&rdquo;</li>
        </ul></li>
    <li>For example, say a carrier (with capacity four) is in the space area of a system along with four fighters. On the only planet in that system are eight infantry. There are no other units in the system. When the carrier moves out of the system, it obeys the following:<sup>5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>5</sup> Designer ruling: &ldquo;No, you cannot exceed a unit&rsquo;s capacity to intentionally destroy units. You would have to leave some of them on the planet in this case.&rdquo;</li>
        </ul></li>
    <li>The carrier may transport the four fighters, leaving behind all eight of the infantry in the system.<sup>2,5</sup>
        <ul>
        <li><b>Implicit</b>: <sup>5</sup> Designer ruling: &ldquo;you are allowed to choose what to transport and leave other stuff behind&rdquo;</li>
        </ul></li>
    <li>The carrier may transport four of the eight infantry, leaving behind the four remaining infantry in the system. Now that the system has zero capacity, all four of the fighters will be removed.<sup>2,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>5</sup> Designer ruling: &ldquo;you CAN pick up 4 infantry and leave the system, causing the fighters to die.&rdquo;</li>
        </ul></li>
    <li>The carrier may transport two of the eight infantry and two of the four fighters, leaving behind the six remaining infantry in the system. Now that the system has zero capacity, the two remaining fighters will be removed.<sup>2,5</sup>
        <ul>
        <li><b>Implicit</b>: <sup>5</sup> Designer ruling: &ldquo;you are allowed to choose what to transport and leave other stuff behind&rdquo;</li>
        </ul></li>
    <li>The carrier may transport nothing, leaving behind all eight of the infantry in the system. Now that the system has zero capacity, all four of the fighters will be removed.<sup>2,5</sup>
        <ul>
        <li><b>Implicit</b>: <sup>5</sup> Designer ruling: &ldquo;There is a passive total capacity for the system that determines how many things can exist in the space area&rdquo;</li>
        </ul></li>
    <li>The carrier cannot attempt to pick up all eight infantry, even if it immediately removes four of them (and the fighters).<sup>2,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>5</sup> Designer ruling: &ldquo;No, you cannot exceed a unit&rsquo;s capacity to intentionally destroy units. You would have to leave some of them on the planet in this case.&rdquo;</li>
        </ul></li>
</ul>
