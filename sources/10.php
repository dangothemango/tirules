<h2><a href="/C_action_cards">Action Cards</a></h2>
<ul>
    <li>Only one fighter will be placed in a system containing both a space dock and a ship with capacity.<sup>10</sup>
        <ul>
        <li><b>Explicit</b>: <sup>10</sup> Codex I, Fighter Conscription: &ldquo;Place 1 fighter from your reinforcements in each system that contains 1 or more of your space docks or units that have capacity.&rdquo; One per system.</li>
        </ul></li>
    <li><i>Ghost Squad</i> is played after the active player has assigned which planet each of their ground forces are being committed to.<sup>10</sup>
        <ul>
        <li><b>Explicit</b>: <sup>10</sup> Codex I, Ghost Squad: &ldquo;After a player commits units to land on a planet you control.&rdquo;</li>
        </ul></li>
    <li><i>Ghost Squad</i> may be played whenever ground forces are committed, such as from the <a href="/F_yin">Yin</a> player&rsquo;s <a href="https://twilight-imperium.fandom.com/wiki/The_Yin_Brotherhood#Leaders:~:text=Quantum%20Dissemination"><i>Quantum Dissemination &Omega;</i></a> hero ability.<sup>10</sup>
        <ul>
        <li><b>Implicit</b>: <sup>10</sup> Codex I, Ghost Squad triggers &ldquo;After a player commits units to land on a planet you control,&rdquo; whatever the source of the commitment.</li>
        </ul></li>
    <li><i>Ghost Squad</i> cannot be played in response to abilities that place ground forces on a planet without committing them, such as the <i>Colonial Redistribution</i> agenda.<sup>10</sup>
        <ul>
        <li><b>Implicit</b>: <sup>10</sup> Codex I, Ghost Squad triggers only &ldquo;After a player commits units to land.&rdquo;</li>
        </ul></li>
    <li>A player may move zero ground forces with <i>Ghost Squad</i>.<sup>10</sup>
        <ul>
        <li><b>Explicit</b>: <sup>10</sup> Codex I, Ghost Squad: &ldquo;Move any number of ground forces from any planet you control in the active system.&rdquo;</li>
        </ul></li>
    <li>The speaker will still vote last.<sup>10</sup>
        <ul>
        <li><b>Implicit</b>: <sup>10</sup> Codex I, Hack Election: &ldquo;During this agenda, voting begins with the player to the right of the speaker and continues counterclockwise.&rdquo; voting starts right of speaker, so speaker is last.</li>
        </ul></li>
    <li>A player cannot play <i>Impersonation</i> if they have less than three influence available.<sup>10</sup>
        <ul>
        <li><b>Implicit</b>: <sup>10</sup> Codex I, Impersonation: &ldquo;ACTION: Spend 3 influence to draw 1 secret objective.&rdquo;</li>
        </ul></li>
    <li>A player cannot play <i>Plagiarize</i> if they have less than five influence available.<sup>10</sup>
        <ul>
        <li><b>Implicit</b>: <sup>10</sup> Codex I, Plagiarize: &ldquo;ACTION: Spend 5 influence and choose a non-faction technology owned by 1 of your neighbors.&rdquo;</li>
        </ul></li>
    <li>The active player may still use the <sc>Space Cannon</sc> ability of their units.<sup>10</sup>
        <ul>
        <li><b>Implicit</b>: <sup>10</sup> Codex I, Solar Flare: &ldquo;Other players cannot use SPACE CANNON against your ships.&rdquo; Only other players are restricted.</li>
        </ul></li>
    <li>During the <b>Space Cannon Defense</b> step of an invasion during the same tactical action, other players may use the <sc>Space Cannon</sc> ability of their units.<sup>10</sup>
        <ul>
        <li><b>Implicit</b>: <sup>10</sup> Codex I, Solar Flare limits Space Cannon &ldquo;against your ships.&rdquo; Space Cannon Defense targets ground forces.</li>
        </ul></li>
    <li><i>War Machine</i> may only be used by effects that cause a unit to use its <sc>Production</sc> ability. It cannot be used for other effects that produce units.<sup>10</sup>
        <ul>
        <li><b>Explicit</b>: <sup>10</sup> Codex I, War Machine: &ldquo;When 1 or more of your units use PRODUCTION.&rdquo;</li>
        </ul></li>
</ul>
