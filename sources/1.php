<h2><a href="/R_abilities">Abilities</a></h2>
<ul>
    <li>An ability may be triggered during the timing window it was gained, if applicable. For example, if a player receives the <a href="/F_creuss">Creuss</a> player&rsquo;s <a href="https://twilight-imperium.fandom.com/wiki/The_Ghosts_of_Creuss#Faction_Promissory_Note:~:text=Creuss%20Iff"><i>Creuss Iff</i></a> promissory note at the start of their turn, they may use it immediately.<sup>1,2,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR FAQ: &ldquo;Can a card (such as a promissory note) with a specified timing of a certain window that is acquired from a transaction during that window be played immediately? A: Yes.&rdquo;</li>
        </ul></li>
    <li>All abilities that occur &ldquo;when&rdquo; an event occurs all trigger before any abilities that occur &ldquo;after&rdquo; the same event occurs.<sup>1</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 1.16: &ldquo;Effects that occur &lsquo;when&rsquo; an event happens take priority over effects that occur &lsquo;after&rsquo; an event happens.&rdquo;</li>
        </ul></li>
    <li>An ability from a single physical object cannot be resolved more than once in one timing window. For example, if a player starts their turn with the Creuss player&rsquo;s <i>Creuss Iff</i> promissory note in their hand (having received it on a previous turn) and uses it, they will not be able to use it a second time this turn, if they receive it again as part of a transaction.<sup>1,5</sup>
        <ul>
        <li><b>Implicit</b>: <sup>1</sup> LRR 1.18: &ldquo;Each ability can be resolved once for each occurrence of that ability&rsquo;s timing event.&rdquo;</li>
        </ul></li>
    <li>During the action phase, abilities are resolved in the current relative turn order, starting with the active player. For example, if it is currently the <i>Trade</i> (5) player&rsquo;s turn, they will have the option to resolve first, then the <i>Warfare</i> (6) player, then the <i>Technology</i> (7) player, and so on.<sup>1,2,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 1.19: &ldquo;If there are multiple abilities that players wish to resolve at the same time during the action phase, each player takes a turn resolving an ability in initiative order, beginning with the active player.&rdquo;</li>
        </ul></li>
    <li>If a player has multiple abilities they wish to resolve, they must be resolved one at a time. Between each ability being resolved, each other player will have the opportunity to resolve one ability.<sup>1,2,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 1.19: &ldquo;each player takes a turn resolving an ability &hellip; This process continues until each player has resolved each ability that they wish to resolve.&rdquo;</li>
        </ul></li>
    <li>For example, Alice, the active player, wishes to resolve four abilities during the current timing window. Bob, the next player in order, wishes to resolve one. Cheng, later in the order, wishes to resolve two. The order of resolution would be: Alice &num;1; Bob &num;1; Cheng &num;1; Alice &num;2; Cheng &num;2; Alice &num;3; Alice &num;4.<sup>1</sup>
        <ul>
        <li><b>Implicit</b>: <sup>1</sup> LRR 1.19: players take turns, one ability at a time.</li>
        </ul></li>
    <li>The secondary abilities of strategy cards are resolved in clockwise order, after the primary ability.<sup>1,2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 82.1: &ldquo;After the active player resolves the primary ability on their strategy card, each other player, beginning with the player to the left of the active player and proceeding clockwise, may resolve that card&rsquo;s secondary ability.&rdquo;</li>
        </ul></li>
    <li>A player may resolve &ldquo;at the start of your turn&rdquo; and &ldquo;at the end of your turn&rdquo; abilities on the turn that they pass.<sup>1,4</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 3.3a: &ldquo;During a turn that a player passes, they can resolve transactions and &lsquo;at the start of your turn&rsquo; abilities.&rdquo;</li>
        </ul></li>
</ul>
<h2><a href="/R_action_cards">Action Cards</a></h2>
<ul>
    <li>A player may choose to reveal any or all of the action cards in their hand.<sup>1,2,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR FAQ: &ldquo;Can you intentionally reveal hidden information to another player, such as an action card from your hand &hellip;? A: Yes. This information is kept hidden by default, but it is permissible to reveal it.&rdquo;</li>
        </ul></li>
    <li>If the action card deck is depleted, immediately shuffle the discard pile to form a new action card deck.<sup>1</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 23.5: &ldquo;When a deck is depleted, players shuffle the deck&rsquo;s discard pile and place it facedown to create a new deck.&rdquo;</li>
        </ul></li>
    <li>A player cannot use action cards that destroy units, such as <i>Lucky Shot</i>, against their own units.<sup>1,2,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR FAQ: &ldquo;&rsquo;Lucky Shot&rsquo; and other similar effects can only be used against other player&rsquo;s units and planets.&rdquo;</li>
        </ul></li>
    <li>If a player has more than seven action cards, they must discard the excess.<sup>1,2,3</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 2.4: &ldquo;If a player ever has more than seven action cards, that player must choose seven cards to keep and discard the rest.&rdquo;</li>
        </ul></li>
</ul>
<h2><a href="/R_action_phase">Action Phase</a></h2>
<ul>
    <li>A player may resolve &ldquo;at the start of your turn&rdquo; and &ldquo;at the end of your turn&rdquo; abilities on the turn that they pass.<sup>1,4</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 3.3a: &ldquo;During a turn that a player passes, they can resolve transactions and &lsquo;at the start of your turn&rsquo; abilities.&rdquo;</li>
        </ul></li>
</ul>
<h2><a href="/R_active_player">Active Player</a></h2>
<ul>
    <li>During combat, the active player is the attacker.<sup>1,3</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 13: &ldquo;During combat, the active player is the attacker.&rdquo;</li>
        </ul></li>
    <li>The active player will have the first opportunity to resolve abilities during each timing window.<sup>1,2,5</sup>
        <ul>
        <li><b>Implicit</b>: <sup>1</sup> LRR 1.19: abilities are resolved &ldquo;in initiative order, beginning with the active player.&rdquo;</li>
        </ul></li>
    <li>If a non&ndash;active player produces hits using the <sc>Space Cannon Offense</sc> ability of one of their units, those hits must be assigned to the active player&rsquo;s units.<sup>1,2</sup>
        <ul>
        <li><b>Implicit</b>: <sup>1</sup> LRR 77.5: &ldquo;The player whose units have been targeted by &lsquo;Space Cannon&rsquo; must choose and destroy one of their ships.&rdquo;</li>
        </ul></li>
</ul>
<h2><a href="/R_adjacency">Adjacency</a></h2>
<ul>
    <li>A unit is not adjacent to the system it is in.<sup>1,2</sup>
        <ul>
        <li><b>Implicit</b>: <sup>1</sup> LRR 6.2a: &ldquo;A unit or planet is adjacent to all system tiles that are adjacent to the system tile that contains that unit or planet. a A system is not adjacent to itself.&rdquo; a system is not adjacent to itself, so a unit in it is not adjacent to it.</li>
        </ul></li>
</ul>
<h2><a href="/R_agenda_phase">Agenda Phase</a></h2>
<ul>
    <li>Casting zero votes for an outcome is the same as abstaining. A player that casts zero votes gains no positive or negative effects of voting for that outcome.<sup>1,2,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR FAQ, Agendas: &ldquo;A vote of zero is the same as abstaining; that player gains no positive or negative effects of voting &lsquo;For&rsquo; or &lsquo;Against&rsquo; on an agenda if they contributed zero votes.&rdquo;</li>
        </ul></li>
    <li>The speaker decides tied outcomes even if they cannot vote on that agenda, such as when they are the <a href="/F_nekro">Nekro</a> player or have played a rider, as deciding a tie is not a vote.<sup>2</sup>
        <ul>
        <li><b>Implicit</b>: <sup>1</sup> LRR 8.19: &ldquo;If there is a tie &hellip; the speaker decides which of the tied outcomes to resolve.&rdquo; No exception for a speaker who cannot vote.</li>
        </ul></li>
    <li>Riders are resolved after the agenda is fully resolved, in speaker order.<sup>1,2</sup>
        <ul>
        <li><b>Implicit</b>: <sup>1</sup> LRR 8.22b: &ldquo;After resolving the outcome of the agenda, any abilities that were dependent upon predicting the outcome are resolved.&rdquo; LRR 1.20 gives speaker order for simultaneous abilities in the agenda phase.</li>
        </ul></li>
    <li>If a player successfully predicts multiple riders, they resolve one at a time, in the order that player chooses, with each other player having the opportunity to resolve an ability between each.<sup>1</sup>
        <ul>
        <li><b>Implicit</b>: <sup>1</sup> LRR 1.20: players &ldquo;take turns resolving abilities starting with the speaker and proceeding clockwise. This process continues until each player has resolved each ability that they wish to resolve during that window.&rdquo; Turn-taking implies one at a time. No source states that the player chooses the order.</li>
        </ul></li>
    <li>Each pair of players may resolve one transaction during each agenda.<sup>1,2,3</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 94.6: &ldquo;While resolving each agenda during the agenda phase, a player may perform one transaction with each other player.&rdquo;</li>
        </ul></li>
    <li>Planets are readied at the end of the agenda phase; other exhausted cards, such as technologies and agents, stay exhausted.<sup>2</sup>
        <ul>
        <li><b>Implicit</b>: <sup>1</sup> LRR 8.4: &ldquo;Step 3&mdash;Ready Planets: Each player readies each of their exhausted planets.&rdquo; Names only planets.</li>
        </ul></li>
</ul>
<h2><a href="/R_anti_fighter_barrage">Anti&ndash;Fighter Barrage (Unit Ability)</a></h2>
<ul>
    <li>A non&ndash;fighter ship cannot use its <sc>Sustain Damage</sc> ability to cancel a hit produced by an anti&ndash;fighter barrage roll, unless an effect such as the <i>Waylay</i> action card makes it eligible to be hit.<sup>1,2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 87.4a: &ldquo;A unit can only use the &lsquo;Sustain Damage&rsquo; ability if it is eligible to be hit. For example, a player cannot use a dreadnought&rsquo;s &lsquo;Sustain Damage&rsquo; ability to cancel a hit from &lsquo;Anti-Fighter Barrage.&rsquo;&rdquo;</li>
        </ul></li>
    <li>The &ldquo;0&rdquo; side of the d10 represents a result of 10.<sup>1,2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR FAQ: &ldquo;Are the &lsquo;0&rsquo; faces of the ten-sided dice &hellip; intended to represent the result of a &lsquo;10&rsquo;? A: Yes, the &lsquo;0&rsquo; face is a &lsquo;10&rsquo; result.&rdquo;</li>
        </ul></li>
</ul>
<h2><a href="/R_attacker">Attacker</a></h2>
<ul>
    <li>The attacker&rsquo;s opponent is the defender.<sup>1,3</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 29: &ldquo;During either a space or ground combat, the player who is not the active player is the defender.&rdquo;</li>
        </ul></li>
</ul>
<h2><a href="/R_blockaded">Blockaded</a></h2>
<ul>
    <li>While a player is involved in a space combat in a system, their units in that system are not blockaded, as both players will have ships in the system.<sup>1,2</sup>
        <ul>
        <li><b>Implicit</b>: <sup>1</sup> LRR 14: &ldquo;A player&rsquo;s unit with &ldquo;Production&rdquo; is blockaded if it is in a system that does not contain any of their ships and contains other players&rsquo; ships.&rdquo; in combat both players have ships there, so the blockade condition fails.</li>
        </ul></li>
</ul>
<h2><a href="/R_bombardment">Bombardment (Unit Ability)</a></h2>
<ul>
    <li>Only the active player may bombard.<sup>1,4</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 15.1: &ldquo;The active player chooses which planet each of their units that has a &lsquo;Bombardment&rsquo; ability will bombard.&rdquo;</li>
        </ul></li>
    <li>The <b>Bombardment</b> step happens outside of combat. No combat effects may affect a bombardment roll.<sup>2</sup>
        <ul>
        <li><b>Implicit</b>: <sup>1</sup> LRR 15.1c: &ldquo;Game effects that reroll, modify, or otherwise affect combat rolls do not affect bombardment rolls.&rdquo;</li>
        </ul></li>
    <li>A single planet must be chosen for each unit with the <sc>Bombardment</sc> ability; any hits generated by that unit will be assigned to units on that planet.<sup>1,2,3</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 15.1d: &ldquo;a player must declare which planet a unit is bombarding before making a bombardment roll.&rdquo;</li>
        </ul></li>
    <li>Mechs may use their <sc>Sustain Damage</sc> ability to cancel a hit produced by a bombardment roll.<sup>2</sup>
        <ul>
        <li><b>Implicit</b>: <sup>1</sup> LRR 87.4: &ldquo;A unit can use its &lsquo;Sustain Damage&rsquo; ability any time a hit is produced against it.&rdquo;</li>
        </ul></li>
    <li>The &ldquo;0&rdquo; side of the d10 represents a result of 10.<sup>1,2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR FAQ: &ldquo;Are the &lsquo;0&rsquo; faces of the ten-sided dice &hellip; intended to represent the result of a &lsquo;10&rsquo;? A: Yes, the &lsquo;0&rsquo; face is a &lsquo;10&rsquo; result.&rdquo;</li>
        </ul></li>
</ul>
<h2><a href="/R_capacity">Capacity (Attribute)</a></h2>
<ul>
    <li>Capacity is checked after the winner of a space combat is determined. It is possible to win a space combat with only fighters remaining, before those fighters are removed due to lack of capacity.<sup>1</sup>
        <ul>
        <li><b>Implicit</b>: <sup>1</sup> LRR 78.10a: &ldquo;If the winner of the combat has fighters or ground forces in the space area of the active system and those units exceed the capacity of that player&rsquo;s ships in that system, that player must choose and remove any excess units.&rdquo; The winner is decided before the excess is removed; fighters are ships, so a side with only fighters remaining is the winner.</li>
        </ul></li>
</ul>
<h2><a href="/R_capture">Capture</a></h2>
<ul>
    <li>Units are returned as soon as a space dock is blockaded.<sup>1,2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 14.2: &ldquo;When a player blockades another player&rsquo;s space dock, if the blockaded player has captured any of the blockading player&rsquo;s units, those units are returned to the blockading player&rsquo;s reinforcements.&rdquo;</li>
        </ul></li>
    <li>A captured unit may only be returned to the player that originally owned it.<sup>1</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 17.1: &ldquo;When such a unit is returned, it is placed into the reinforcements of the original owner.&rdquo;</li>
        </ul></li>
    <li>If a player has all of their units of one type on the game board or captured, and so have none in their reinforcements, and would place a unit of that type, they may remove a unit from any system on the game board that does not contain one of their command tokens and place that unit in their reinforcements, before placing that unit on the game board.<sup>1</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 23.4a: &ldquo;When a player would place a unit, if there are none of that type left in their reinforcements, that player can remove a unit from any system that does not contain one of their command tokens.&rdquo;</li>
        </ul></li>
    <li>A player cannot capture fighter or infantry tokens corresponding to units belonging to a player that is blockading one of their space docks.<sup>1,8</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 17.6: &ldquo;If one or more of a player&rsquo;s space docks is being blockaded, that player cannot capture units from the blockading players.&rdquo;</li>
        </ul></li>
</ul>
<h2><a href="/R_coexistence">Coexistence</a></h2>
<ul>
    <li>Structure limits apply to each player separately. A planet in coexistence may contain up to two PDS and one space dock belonging to each player.<sup>1,4</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 85.4: &ldquo;A player can have a maximum of one space dock on each planet.&rdquo;</li>
        <li><b>Explicit</b>: <sup>1</sup> LRR 85.5: &ldquo;A player can have a maximum of two PDS units on each planet.&rdquo;</li>
        </ul></li>
</ul>
