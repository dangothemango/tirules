<h2><a href="/R_control">Control</a></h2>
<ul>
    <li>Control tokens are not component limited.<sup>1</sup>
        <ul>
        <li><b>Implicit</b>: <sup>1</sup> LRR 72.1: &ldquo;The components in a player&rsquo;s reinforcements are limited.&rdquo; Reinforcements are units and command tokens; control tokens are not listed.</li>
        </ul></li>
</ul>
<h2><a href="/R_cost">Cost (Attribute)</a></h2>
<ul>
    <li>Whenever a unit is produced, its cost must be paid, unless the effect that is producing the unit explicitly says otherwise.<sup>1,2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR FAQ: &ldquo;a unit that is produced must always be paid for.&rdquo; The cited LRR passage (30.1) is less direct.</li>
        </ul></li>
    <li>A player does not have to pay a unit&rsquo;s cost to resolve that unit&rsquo;s <sc>Deploy</sc> ability. However, the <sc>Deploy</sc> ability itself may have a cost that must be paid.<sup>1</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 30.1a: &ldquo;A player does not have to spend resources to deploy a unit unless otherwise specified.&rdquo;</li>
        </ul></li>
</ul>
<h2><a href="/R_deploy">Deploy</a></h2>
<ul>
    <li>A player may only resolve a deploy ability to place a unit that is in their reinforcements. A player cannot remove a unit from the board to use its deploy ability.<sup>1,8</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 30.2: &ldquo;A player can only resolve a deploy ability to place a unit that is in their reinforcements.&rdquo;</li>
        <li><b>Explicit</b>: <sup>1</sup> LRR 30.2a: &ldquo;If there are no units that have a deploy ability in a player&rsquo;s reinforcements, the deploy ability cannot be used.&rdquo;</li>
        </ul></li>
</ul>
<h2><a href="/R_destroyed">Destroyed</a></h2>
<ul>
    <li>Ships that are removed because they exceed a player&rsquo;s fleet pool limit are not destroyed.<sup>1</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 61.9a: &ldquo;Forcing a player to remove a unit from the board by reducing the number of command tokens in their fleet pool is not treated as destroying a unit.&rdquo;</li>
        <li><b>Implicit</b>: <sup>1</sup> LRR 37.3: &ldquo;If at any time the number of a player&rsquo;s non-fighter ships in a system exceeds the number of tokens in that player&rsquo;s fleet pool, they choose and remove excess ships in that system, returning those units to their reinforcements.&rdquo;</li>
        </ul></li>
</ul>
<h2><a href="/R_diplomacy">Diplomacy (Strategy Card)</a></h2>
<ul>
