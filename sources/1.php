<h2><a href="/R_command_sheet">Command Sheet</a></h2>
<ul>
    <li>When a command token is gained, it may be placed in any of the three pools if no specific pool is specified by the gaining effect.<sup>1,2,3</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 52.4: &ldquo;When a player gains command tokens, that player places each token on their command sheet in the pool of their choice.&rdquo;</li>
        </ul></li>
</ul>
<h2><a href="/R_command_tokens">Command Tokens</a></h2>
<ul>
    <li>Players do not spend command tokens from their fleet pool unless a game effect specifically allows it.<sup>1</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 37.4: &ldquo;Players do not spend command tokens from this pool unless a game effect specifically allows it.&rdquo;</li>
        </ul></li>
</ul>
<h2><a href="/R_commodities">Commodities</a></h2>
<ul>
    <li>If a player has their maximum number of commodities, and is instructed to replenish their commodities, they will take no commodities. However, they will still trigger any &ldquo;when [this] player replenishes commodities&rdquo; effects, most notably the <i>Trade Agreement</i> promissory note.<sup>1,2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR FAQ: &ldquo;Even if that player gains zero commodities when their commodities are refreshed, their &lsquo;Trade Agreement&rsquo; may still be played against them.&rdquo;</li>
        </ul></li>
</ul>
<h2><a href="/R_component_action">Component Action</a></h2>
<ul>
    <li>Action cards without the &ldquo;Action&rdquo; header are not used to perform component actions.<sup>1</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 22.1: &ldquo;Each component action is indicated by an &lsquo;Action&rsquo; header.&rdquo;</li>
        </ul></li>
</ul>
<h2><a href="/R_component_limitations">Component Limitations</a></h2>
<ul>
    <li>Players may swap between three value tokens and one value tokens as desired.<sup>1</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 46.4: &ldquo;Infantry tokens come in values of one and three. A player can swap between these tokens as necessary.&rdquo;</li>
        </ul></li>
    <li>A player may only resolve a deploy ability to place a unit that is in their reinforcements. A player cannot remove a unit from the board to use its deploy ability.<sup>1,8</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 30.2: &ldquo;A player can only resolve a deploy ability to place a unit that is in their reinforcements.&rdquo;</li>
        <li><b>Explicit</b>: <sup>1</sup> LRR 30.2a: &ldquo;If there are no units that have a deploy ability in a player&rsquo;s reinforcements, the deploy ability cannot be used.&rdquo;</li>
        </ul></li>
    <li>When a discard pile is shuffled to form a new deck, any cards that have been purged are not included.<sup>1</sup>
        <ul>
        <li><b>Implicit</b>: <sup>1</sup> LRR 70.1: &ldquo;If an ability instructs a player to purge a component, that component is removed from the game and returned to the box.&rdquo; purged cards are out of the game, so not in the discard pile.</li>
        </ul></li>
</ul>
