        <ul>
        <li><b>Explicit</b>: <sup>9</sup> Designer Q&amp;A, &ldquo;Coexistence and PRODUCTION&rdquo;: &ldquo;Coexisting units can produce ground forces but are always blockaded and cannot produce ships.&rdquo;</li>
        </ul></li>
</ul>
<h2><a href="/R_coexistence">Coexistence</a></h2>
<ul>
    <li>Structures without ground forces may coexist on a planet by themselves, and may maintain control of a planet while another player&rsquo;s ground forces coexist on it.<sup>9</sup>
        <ul>
        <li><b>Explicit</b>: <sup>9</sup> Designer Q&amp;A, &ldquo;Coexistence and Structures&rdquo;: &ldquo;Structures without ground forces may maintain control of a planet with coexisting ground forces. Structures without ground forces may coexist by themselves.&rdquo;</li>
        </ul></li>
    <li>If only one player has units on a planet that was in coexistence, and that player was coexisting, they gain control of that planet.<sup>6,7,9</sup>
        <ul>
        <li><b>Implicit</b>: <sup>9</sup> Designer Q&amp;A, &ldquo;Coexistence Control Default (With Multiple Coexisting Players).&rdquo;</li>
        </ul></li>
    <li>During an invasion, if the last of the controlling player&rsquo;s units on a planet are destroyed, such as by <sc>Bombardment</sc>, control does not pass to the coexisting player until the <b>Establish Control</b> step. The invading player may land ground forces and gain control of the planet, and the coexisting player remains in coexistence.<sup>6,9</sup>
        <ul>
        <li><b>Explicit</b>: <sup>9</sup> Designer Q&amp;A, &ldquo;Coexist Control Default (During Invasions)&rdquo;: &ldquo;During invasion, control default due to coexistence does not occur until the establish control step. The invading player may land ground forces and take control of the planet.&rdquo;</li>
        </ul></li>
    <li>If multiple players are coexisting on a planet and the player that controls that planet no longer has units on it, control passes to the next coexisting player in the order used to resolve abilities in the current phase: initiative order during the action phase, otherwise clockwise order.<sup>6,9</sup>
        <ul>
        <li><b>Explicit</b>: <sup>9</sup> Designer Q&amp;A, &ldquo;Coexistence Control Default (With Multiple Coexisting Players)&rdquo;: &ldquo;Control defaults to the next player in order as per ability resolution order by phase (initiative order during action phase, otherwise clockwise).&rdquo;</li>
        </ul></li>
    <li>All coexisting units are blockaded, regardless of what ships, if any, are in the system. This includes units that are not structures, such as mechs with the <sc>Production</sc> ability.<sup>2,6,7,9</sup>
        <ul>
        <li><b>Explicit</b>: <sup>9</sup> Designer Q&amp;A: &ldquo;Coexisting units &hellip; are always blockaded.&rdquo;</li>
        <li><b>Explicit</b>: <sup>9</sup> Designer Q&amp;A, &ldquo;Coexistence and PRODUCTION&rdquo;: &ldquo;Coexisting units can produce ground forces but are always blockaded and cannot produce ships.&rdquo;</li>
        </ul></li>
    <li>Coexisting units may use their <sc>Production</sc> ability to produce ground forces, but cannot produce ships.<sup>9</sup>
        <ul>
        <li><b>Explicit</b>: <sup>9</sup> Designer Q&amp;A, &ldquo;Coexistence and PRODUCTION&rdquo;: &ldquo;Coexisting units can produce ground forces but are always blockaded and cannot produce ships.&rdquo;</li>
        </ul></li>
    <li>When scoring an objective, a coexisting player considers both themselves and the controlling player to control that planet. The player that controls the planet does not count a coexisting player as also controlling it.<sup>2,6,7,9</sup>
        <ul>
        <li><b>Explicit</b>: <sup>9</sup> Designer Q&amp;A, &ldquo;Coexistence, Perspective During Scoring&rdquo;: &ldquo;the coexisting player sees both themselves and the controlling player as controlling that planet when scoring objectives.&rdquo;</li>
        <li><b>Explicit</b>: <sup>9</sup> Designer Q&amp;A, &ldquo;Coexistence, Perspective During Scoring&rdquo;: &ldquo;Only the coexisting player counts themselves as controlling that planet. The player the coexisting player is coexisting with does not count the coexisting player as also controlling that planet.&rdquo;</li>
        </ul></li>
    <li>A player may score public objectives even if they coexist on, but do not control, each planet in their home system.<sup>6,9</sup>
        <ul>
        <li><b>Explicit</b>: <sup>9</sup> Designer Q&amp;A, &ldquo;Scoring Public Objectives Coexisting At Home&rdquo;: &ldquo;Yes, you may score public objectives even if you coexist on but do not outright control each planet in your home system.&rdquo;</li>
        </ul></li>
    <li>A player must control a planet, not merely coexist on it, to explore it.<sup>6,9</sup>
        <ul>
        <li><b>Explicit</b>: <sup>9</sup> Designer Q&amp;A, &ldquo;Coexist and Exploration&rdquo;: &ldquo;You must control a planet outright to explore it.&rdquo;</li>
        </ul></li>
    <li>A player cannot spend another player&rsquo;s coexisting units to pay the cost of an exploration card, such as <i>Volatile Fuel Source</i>.<sup>9</sup>
        <ul>
        <li><b>Explicit</b>: <sup>9</sup> Same answer: &ldquo;You cannot spend other player&rsquo;s units to pay for explore cards&rsquo; costs.&rdquo;</li>
        </ul></li>
</ul>
